    private void jButtonAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAddActionPerformed
         int row = jTableShowCourse.getSelectedRow();

    if (row == -1) {
        jLabelInfo.setText("Please select a course first.");
        return;
    }

    // Get selected course ID
    String courseId = jTableShowCourse.getValueAt(row, 0).toString();

    // loggedStudentId was passed from login screen
    RegistrationDAO dao = RegistrationDAO.getInstance();
    dao.addRegistration(loggedStudentId, courseId);

    jLabelInfo.setText("course Added");
    }//GEN-LAST:event_jButtonAddActionPerformed

    private void jTableShowCourseMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableShowCourseMouseClicked
        int row = jTableShowCourse.getSelectedRow();
    if (row != -1) {
        String courseId = jTableShowCourse.getValueAt(row, 0).toString();
        String courseName = jTableShowCourse.getValueAt(row, 1).toString();

        jTextCourseId.setText(
            "Course ID: " + courseId + "\nCourse Name: " + courseName
        );
    }
    }//GEN-LAST:event_jTableShowCourseMouseClicked

