    private void jButtonShowAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonShowAllActionPerformed
         try {
        CourseDAO dao = new CourseDAO();
        List<Course> list = dao.getCisCourses();

        DefaultTableModel model =
            new DefaultTableModel(new Object[]{"Course ID", "Course Name", "Credit Hours"}, 0);

        for (Course c : list) {
            model.addRow(new Object[]{
                c.getCourseId(), c.getCourseName(), c.getCreditHours()
            });
        }
        System.out.println("Loading CIS courses...");
        System.out.println("Rows found: " + list.size());

       jTableShowCourse.setModel(model);

    } catch (Exception e) {
        e.printStackTrace();
        jLabelInfo.setText("Error loading courses!");
    }
    }//GEN-LAST:event_jButtonShowAllActionPerformed

