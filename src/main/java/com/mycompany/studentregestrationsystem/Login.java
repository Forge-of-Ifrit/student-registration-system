    private void jButtonLoginActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonLoginActionPerformed
       String id = jTextId.getText();
       String pass = jTextPass.getText();

    // Optional: you can add role if you created a JCombobox
    // For now we detect using DB (recommended)

    if (id.isEmpty() || pass.isEmpty()) {
        jLabelinfo.setText("Please enter ID and Password");
        return;
    }

    LoginDAO loginDAO = new LoginDAO();
    String role = loginDAO.checkRole(id, pass);   // student / advisor / null

    if (role == null) {
        jLabelinfo.setText("Invalid ID or Password!");
        return;
    }

    // SUCCESS
    jLabelinfo.setText("Login Successful as: " + role.toUpperCase());

    // Open the correct GUI
    if (role.equals("student")) {
        new StudentGUI(id).setVisible(true);
        this.dispose();
    } 
    else if (role.equals("advisor")) {
        new AdvisorGUI().setVisible(true);
        this.dispose();
    }
    }//GEN-LAST:event_jButtonLoginActionPerformed

