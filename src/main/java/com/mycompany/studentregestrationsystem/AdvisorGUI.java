    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
    RegistrationDAO dao = RegistrationDAO.getInstance();
    List<Registration> list = dao.getAllRegistrations();

    DefaultTableModel model = new DefaultTableModel(
        new Object[]{"Reg ID", "Student ID", "Course ID", "Status"}, 0
    );

    for (Registration r : list) {
        model.addRow(new Object[]{
            r.getRegId(),
            r.getStudentId(),
            r.getCourseId(),
            r.getStatus()
        });
    }

    jTableShowRegistered.setModel(model);
    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        if (selectedRegId == -1) {
        jLabelStatus.setText("Please select a registration first.");
        return;
    }

    RegistrationDAO dao = RegistrationDAO.getInstance();
    if (dao.updateStatus(selectedRegId, "Approved")) {
        jLabelStatus.setText("Current Status: Approved");
        
    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jTableShowRegisteredMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTableShowRegisteredMouseClicked
        int row = jTableShowRegistered.getSelectedRow();

    if (row != -1) {
        int regId = Integer.parseInt(jTableShowRegistered.getValueAt(row, 0).toString());
        String studentId = jTableShowRegistered.getValueAt(row, 1).toString();
        String courseId = jTableShowRegistered.getValueAt(row, 2).toString();
        String status = jTableShowRegistered.getValueAt(row, 3).toString();

        jTextFieldStudentID.setText(studentId);
        jTextFieldCourseID.setText(courseId);
        jLabelStatus.setText("Current Status: " + status);

        // Save registered ID for update buttons
        selectedRegId = regId;
    }
    }//GEN-LAST:event_jTableShowRegisteredMouseClicked

